#!/usr/bin/env python3
"""Convert the pinned public-domain SQLite Unicode 6.1 tables to Go."""
import ast
import hashlib
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[2]
source = ROOT / "tools/fts5/sqlite/fts5_unicode2.c"
manifest = json.loads(source.with_name("manifest.json").read_text())
assert hashlib.sha256(source.read_bytes()).hexdigest() == manifest["sha256"], "source checksum differs"
text = source.read_text()


def body(name):
    return re.search(r"\b" + name + r"\[\]\s*=\s*\{(.*?)\};", text, re.S)[1]


def numbers(name):
    return list(map(int, re.findall(r"\d+", body(name))))


out = ["// Code generated by python3 tools/fts5/unicode_tables.py; DO NOT EDIT.",
       "// SQLite Unicode 6.1, revision " + manifest["revision"] + ".",
       "// Public-domain source and checksum: tools/fts5/sqlite/manifest.json.",
       "package docid\n"]
for src, dst, typ in [("aDia", "unicodeDiacriticRanges", "uint16"), ("aiOff", "unicodeFoldOffsets", "uint16"), ("aFts5UnicodeBlock", "unicodeCategoryBlocks", "uint16"), ("aFts5UnicodeMap", "unicodeCategoryMap", "uint16"), ("aFts5UnicodeData", "unicodeCategoryData", "uint16")]:
    out.append("var " + dst + " = [...]" + typ + "{" + ",".join(map(str, numbers(src))) + ",}\n")
chars = []
for entry in body("aChar").split(","):
    if not entry.strip():
        continue
    char = re.search(r"'(?:\\.|[^'])+'", entry)[0]
    chars.append(ord(ast.literal_eval(char)) | (128 if "HIBIT" in entry else 0))
out.append("var unicodeDiacriticChars = [...]byte{" + ",".join(map(str, chars)) + ",}\n")
entries = re.findall(r"\{(\d+),\s*(\d+),\s*(\d+)\}", body("aEntry"))
out.append("var unicodeFoldRanges = [...][3]uint16{" + ",".join("{" + ",".join(e) + "}" for e in entries) + ",}\n")
destination = ROOT / "unicode61_tables.go"
destination.write_text("\n".join(out))
subprocess.run(["gofmt", "-w", str(destination)], check=True)
